async function seedQuestions() {
  console.log('🌱 Seeding user questions...');

  let createdCount = 0;
  for (const q of USER_QUESTIONS) {
    const existing = await prisma.question.findFirst({
      where: { text: q.text },
    });

    if (!existing) {
      await prisma.question.create({ data: q });
      createdCount++;
    } else {
      await prisma.question.update({
        where: { id: existing.id },
        data: q,
      });
    }
  }

  const totalInDb = await prisma.question.count();
  const codingCount = await prisma.question.count({ where: { type: 'CODING' } });
  const mcqCount = await prisma.question.count({ where: { type: 'MCQ' } });
  const snakeCount = await prisma.question.count({ where: { isSnakeQuestion: true } });
  const ladderCount = await prisma.question.count({ where: { isLadderQuestion: true } });

  console.log(`✅ Questions seeded! Inserted/updated ${USER_QUESTIONS.length} questions (new: ${createdCount}).`);
  console.log(`📊 Total questions in database: ${totalInDb}`);
  console.log(`   • Coding questions: ${codingCount}`);
  console.log(`   • MCQ / Prediction questions: ${mcqCount}`);
  console.log(`   • Snake dodge questions: ${snakeCount}`);
  console.log(`   • Ladder climb questions: ${ladderCount}`);
}

if (require.main === module) {
  seedQuestions()
    .then(() => {
      process.exit(0);
    })
    .catch((err) => {
      console.error('❌ Error seeding questions:', err);
      process.exit(1);
    });
}

